import AppKit
import Carbon.HIToolbox
import Observation
import OSLog

/// One thing that was on the general pasteboard. `items` is every
/// representation the source app wrote, byte for byte, so putting it back gives
/// the next paste the same rich text, image or file list the copy did — not a
/// flattened string.
struct Clip: Identifiable {
    enum Kind { case text, link, image, file }

    let id = UUID()
    let kind: Kind
    /// One line, whitespace folded. The row cuts it; the latest card wraps it.
    let preview: String
    let thumbnail: NSImage?
    let items: [[NSPasteboard.PasteboardType: Data]]
    let copiedAt: Date
    /// Same content copied twice is one clip, moved up. Files and images hash
    /// off the bytes, not the preview — two different images can preview the
    /// same. Text hashes off its trimmed string alone.
    let signature: Int
}

/// The clipboard history behind the panel's Clipboard page: the last few
/// copies, newest first, and the way to put one back — and paste it.
///
/// In memory only. A clipboard holds whatever was copied, including what a
/// password manager chose not to mark; writing it to disk would turn a
/// convenience into a record nobody asked to keep.
@Observable
@MainActor
final class ClipboardHistory {
    private nonisolated static let log = Logger(subsystem: "com.polkka.Vitals", category: "clipboard")

    /// The page shows four; the rest are there for a later list. Twenty also
    /// bounds memory — a full-screen screenshot is several MB of TIFF.
    static let capacity = 20
    /// Past this a copy is not kept. A clip is held in memory in full, and a
    /// 4K screenshot or a pasted video would pin that much for the session.
    /// ponytail: one ceiling for every type; a per-type cap (keep big images,
    /// drop big blobs) is the upgrade if screenshots start falling off.
    static let maxBytes = 12 * 1024 * 1024

    private(set) var clips: [Clip] = []
    /// What a paste would produce right now. Moves on a fresh copy and on a
    /// put-back; the list itself never reorders on a put-back, so the row you
    /// pressed is still under the pointer.
    private(set) var liveID: UUID?

    private let pasteboard = NSPasteboard.general
    private var seen = 0
    private var timer: Timer?

    // MARK: Watching

    /// The pasteboard posts nothing when it changes — no notification, no KVO —
    /// so this reads `changeCount`, one integer, on a slack timer. The same
    /// trade `lifecycles.md` makes for CPU: no dependable push, so a cheap read.
    /// The contents are read only when the count moves.
    func start() {
        guard timer == nil else { return }
        seen = pasteboard.changeCount
        // Whatever is on the clipboard at launch is the floor, so the page
        // opens on something true rather than on "Nothing copied".
        capture()
        let timer = Timer(timeInterval: 1, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.tick() }
        }
        timer.tolerance = 0.5
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    private func tick() {
        let count = pasteboard.changeCount
        guard count != seen else { return }
        seen = count
        capture()
    }

    private func capture() {
        guard let pbItems = pasteboard.pasteboardItems, !pbItems.isEmpty else { return }
        let types = Set(pbItems.flatMap(\.types).map(\.rawValue))
        // nspasteboard.org's markers: password managers set Concealed, apps
        // that write a value only to hand it straight on set Transient or
        // AutoGenerated. None of them is a copy the user would want back.
        if !types.isDisjoint(with: Self.skipped) { return }

        var bytes = 0
        var items: [[NSPasteboard.PasteboardType: Data]] = []
        for item in pbItems {
            var reps: [NSPasteboard.PasteboardType: Data] = [:]
            for type in item.types {
                guard let data = item.data(forType: type) else { continue }
                bytes += data.count
                if bytes > Self.maxBytes {
                    Self.log.info("skipped a \(bytes) byte copy")
                    return
                }
                reps[type] = data
            }
            if !reps.isEmpty { items.append(reps) }
        }
        guard let clip = Self.clip(from: items) else { return }

        clips.removeAll { $0.signature == clip.signature }
        clips.insert(clip, at: 0)
        if clips.count > Self.capacity { clips.removeLast(clips.count - Self.capacity) }
        liveID = clip.id
    }

    private static let skipped: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
    ]

    // MARK: Reading a copy

    /// Files beat images beat text: a Finder copy carries the icon as a TIFF
    /// and the name as a string beside the URL, and the URL is what was meant.
    private static func clip(from items: [[NSPasteboard.PasteboardType: Data]]) -> Clip? {
        var hasher = Hasher()
        for item in items {
            for type in item.keys.sorted(by: { $0.rawValue < $1.rawValue }) {
                hasher.combine(type.rawValue)
                hasher.combine(item[type])
            }
        }
        let signature = hasher.finalize()
        let now = Date()

        let files = items.compactMap { $0[.fileURL] }
            .compactMap { URL(dataRepresentation: $0, relativeTo: nil) }
        if !files.isEmpty {
            let name = files[0].lastPathComponent
            let preview = files.count == 1 ? name : "\(name) and \(files.count - 1) more"
            return Clip(kind: .file, preview: preview, thumbnail: nil, items: items,
                        copiedAt: now, signature: signature)
        }

        if let data = items.lazy.compactMap({ $0[.png] ?? $0[.tiff] }).first,
           let image = NSImage(data: data) {
            let px = image.representations.first.map { CGSize(width: $0.pixelsWide, height: $0.pixelsHigh) }
                ?? image.size
            return Clip(kind: .image, preview: "Image \(Int(px.width)) × \(Int(px.height))",
                        thumbnail: thumbnail(image), items: items, copiedAt: now, signature: signature)
        }

        guard let data = items.lazy.compactMap({ $0[.string] }).first,
              let raw = String(data: data, encoding: .utf8) else { return nil }
        // Folded to one line: a row has one, and the card's wrap should come
        // from its width, not from the source's line breaks.
        let folded = raw.split(whereSeparator: \.isWhitespace).joined(separator: " ")
        guard !folded.isEmpty else { return nil }
        let preview = String(folded.prefix(300))
        let trimmed = raw.trimmingCharacters(in: .whitespacesAndNewlines)
        let link = !trimmed.contains(where: \.isWhitespace) && Self.isLink(trimmed)
        // Text is the same copy when its trimmed string is. Hashing every
        // representation split it: apps write extras beside the string (a
        // source URL, a timestamped RTF) that change between two copies of the
        // same words, and the page showed the same row twice.
        return Clip(kind: link ? .link : .text, preview: preview, thumbnail: nil,
                    items: items, copiedAt: now, signature: trimmed.hashValue)
    }

    private static func isLink(_ s: String) -> Bool {
        guard let url = URL(string: s), let scheme = url.scheme?.lowercased() else { return false }
        return (scheme == "http" || scheme == "https") && url.host != nil
    }

    /// Kept small so twenty clips never hold twenty full-size images twice.
    private static func thumbnail(_ image: NSImage) -> NSImage {
        let side: CGFloat = 64
        let scale = min(side / max(image.size.width, 1), side / max(image.size.height, 1), 1)
        let size = CGSize(width: image.size.width * scale, height: image.size.height * scale)
        return NSImage(size: size, flipped: false) { rect in
            image.draw(in: rect)
            return true
        }
    }

    // MARK: Putting one back

    /// Writes the clip back exactly as it was copied. The count this write
    /// produces is marked seen, so the watcher does not file Vitals' own write
    /// as a new copy and move the row out from under the pointer.
    func restore(_ clip: Clip) {
        pasteboard.clearContents()
        let items = clip.items.map { reps -> NSPasteboardItem in
            let item = NSPasteboardItem()
            for (type, data) in reps { item.setData(data, forType: type) }
            return item
        }
        pasteboard.writeObjects(items)
        seen = pasteboard.changeCount
        liveID = clip.id
    }

    /// Whether a ⌘V sent now would land. Posting keys needs the Accessibility
    /// grant Vitals already asks for (`BuildWatcher`); secure input — a
    /// password field has focus — drops synthetic keys, so there it is copy
    /// only rather than a paste that silently goes nowhere.
    var canPaste: Bool { AXIsProcessTrusted() && !IsSecureEventInputEnabled() }

    /// ⌘V into whatever app has focus. The panel is non-activating, so that is
    /// still the app the user was typing in. The delay lets the panel's shrink
    /// start and the pasteboard write settle before the target reads it.
    func pasteSoon() {
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.05) {
            let source = CGEventSource(stateID: .combinedSessionState)
            let v = CGKeyCode(kVK_ANSI_V)
            let down = CGEvent(keyboardEventSource: source, virtualKey: v, keyDown: true)
            let up = CGEvent(keyboardEventSource: source, virtualKey: v, keyDown: false)
            down?.flags = .maskCommand
            up?.flags = .maskCommand
            down?.post(tap: .cghidEventTap)
            up?.post(tap: .cghidEventTap)
        }
    }
}
